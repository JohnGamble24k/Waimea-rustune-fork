const LANGUAGE = (navigator.language || 'en').toLowerCase().startsWith('nl') ? 'nl' : 'en';
const T = STRINGS[LANGUAGE];

function translatePage() {
  document.documentElement.lang = LANGUAGE;
  const labels = {
    'library-toggle': 'showLibrary',
    minimize: 'minimize',
    close: 'close',
    winamp: 'classicPlayer',
    library: 'library',
    query: 'search',
    'eq-preset': 'preset',
    position: 'position',
    shuffle: 'shuffle',
    repeat: 'repeat',
    prev: 'previous',
    play: 'play',
    next: 'next',
    volume: 'volume',
  };
  Object.entries(labels).forEach(([id, key]) => document.getElementById(id).setAttribute('aria-label', T[key]));
  document.querySelector('.controls').setAttribute('aria-label', T.controls);
  const texts = {
    'eq-on-label': 'eqOn',
    'add-files': 'addFiles',
    'add-folder': 'addFolder',
    loading: 'loadingSkin',
    title: 'choose',
  };
  Object.entries(texts).forEach(([id, key]) => { document.getElementById(id).textContent = T[key]; });
  const tabs = { local: 'tabLocal', radio: 'tabRadio', queue: 'tabQueue', eq: 'tabEq', skins: 'tabSkins' };
  document.querySelectorAll('[role=tab]').forEach((tab) => { tab.textContent = T[tabs[tab.dataset.source]]; });
}

translatePage();
